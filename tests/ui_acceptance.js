(async () => {
  const passed=[];
  const assert=(condition,label)=>{if(!condition) throw new Error(label); passed.push(label)};
  const wait=async(fn)=>{for(let n=0;n<200;n++){if(fn())return;await new Promise(r=>setTimeout(r,20))}throw new Error('UI timeout')};
  await wait(()=>document.querySelector('#app:not(.hidden)'));
  assert(!!document.querySelector('#workspaceSelect'),'workspace selector exists');
  assert(!!document.querySelector('#generateCharacter'),'explicit persona generation exists');
  assert(document.querySelector('#sec-api').closest('section').id==='tab-connect','credentials stay global');
  assert(document.querySelector('[data-key="llm_model"]').closest('section').id==='tab-ai','model is scoped editorial setting');
  document.querySelector('#workspaceSelect').value='2';
  document.querySelector('#workspaceSelect').dispatchEvent(new Event('change'));
  await wait(()=>document.querySelector('#workspaceName').textContent==='Sport');
  document.querySelector('[data-tab="channels"]').click();
  await wait(()=>document.querySelector('#channelList').textContent.includes('sport_source'));
  assert(!document.querySelector('#channelList').textContent.includes('politics_source'),'switch shows only selected sources');
  document.querySelector('#newChannels').value='politics_source';
  document.querySelector('#addChannels').click();
  await wait(()=>document.querySelector('#channelList').textContent.includes('politics_source'));
  assert(document.querySelector('#channelList').textContent.includes('sport_source'),'duplicate source can be added independently');
  document.querySelector('[data-tab="ai"]').click();
  document.querySelector('#characterKeywords').value='точный, дружелюбный';
  document.querySelector('#generateCharacter').click();
  await wait(()=>document.querySelector('[data-key="persona_custom"]').value.includes('Отделяй факты'));
  assert(document.querySelector('#personaInput').value==='custom','generated instruction is editable custom draft');
  let st=await (await fetch('/api/state',{headers:{'X-Workspace-ID':'2'}})).json();
  assert(st.settings.persona_custom==='','generation never automatically saves');
  document.querySelector('[data-key="persona_custom"]').value='Owner unsaved edit';
  document.querySelector('[data-key="persona_custom"]').dispatchEvent(new Event('input',{bubbles:true}));
  const savedConfirm=window.confirm; let confirmations=0;
  window.confirm=()=>{confirmations++;return false};
  document.querySelector('#generateCharacter').click();
  await new Promise(r=>setTimeout(r,80));
  assert(confirmations===1,'regeneration confirms unsaved edits');
  assert(document.querySelector('[data-key="persona_custom"]').value==='Owner unsaved edit','declining regeneration preserves edits');
  window.confirm=savedConfirm;
  document.querySelector('[data-save="sec-persona"]').click();
  await wait(()=>!document.querySelector('[data-save="sec-persona"]').disabled);
  st=await (await fetch('/api/state',{headers:{'X-Workspace-ID':'2'}})).json();
  assert(st.settings.persona_custom==='Owner unsaved edit','explicit Save applies owner edit');
  assert(document.querySelector('#operationCost').textContent.includes('character_prompt'),'operation type is visible in Costs');
  assert(document.querySelector('#operationCost').textContent.includes('неизвестна'),'unknown spending is not displayed as zero');
  return {passed};
})()