def persona_text(get) -> str:
    pid = get("persona")
    if pid == "custom":
        return get("persona_custom").strip() or PERSONAS["editor"]["text"]
    return PERSONAS.get(pid, PERSONAS["editor"])["text"]


def _values(get, count) -> dict:
    return {
        "persona": persona_text(get),
        "count": count,
        "min_len": get("min_len"),
        "max_len": get("max_len"),
        "emoji": ("Обязательно 1–2 уместных эмодзи. Для трагедий — нейтральный 📰; без сенсационных, весёлых или легкомысленных эмодзи."
                  if get("emoji") == "1" else "Без эмодзи."),
        "style": get("style").strip() or "нет",
        "language": get("language").strip() or "русский",
    }


def render(template: str, values: dict) -> str:
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    return template


def _outlook_values(get):
    return {'outlook_horizon': OUTLOOK_HORIZONS.get(get('news_outlook_horizon'), OUTLOOK_HORIZONS['days_weeks']),
            'outlook_max_len': get('news_outlook_max_len') or '600',
            'outlook_focus': json.dumps(get('news_outlook_focus') or '', ensure_ascii=False)}


def news_outlook_rules(get):
    if get('news_outlook_enabled') == '0':
        return NEWS_OUTLOOK_DISABLED_RULES
    return render(_NEWS_OUTLOOK_TEMPLATE, _outlook_values(get))


def build_propose(get, count, extra: str = "") -> str:
    """extra — добавки от включённых модулей (примеры, особые правила)."""
    values = _values(get, count)
    body = render(get("prompt").strip() or DEFAULT_PROMPT, values)
    if extra.strip():
        body += "\n\n" + extra.strip()
    enabled = get('news_outlook_enabled') != '0'
    suffix = PROPOSE_SUFFIX if enabled else PROPOSE_SUFFIX_NO_OUTLOOK
    return body + "\n\n" + render(suffix, {**values, **_outlook_values(get)}) + "\n\n" + render(FORMAT_RULES, values) + "\n\n" + news_outlook_rules(get)


def build_rewrite(get, extra: str = "") -> str:
    values = _values(get, get("proposals"))
    body = render(REWRITE_PROMPT, values)
    return body + ("\n\n" + extra.strip() if extra.strip() else "") + "\n\n" + render(FORMAT_RULES, values) + "\n\n" + news_outlook_rules(get)
